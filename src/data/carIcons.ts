function slug(value: string): string {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

export function carImageUrl(brand: string, model: string, width = 240): string {
  const make = BRAND_MAKE[brand] ?? slug(brand);
  const family = MODEL_FAMILY[model] ?? slug(model);
  const params = new URLSearchParams({
    customer: 'img',
    make,
    modelFamily: family,
    width: String(Math.max(160, Math.round(width))),
    angle: '23',
    zoomType: 'fullscreen',
    fileType: 'webp',
  });
  if (isElectric(model)) params.set('powerTrain', 'electric');
  return `https://cdn.imagin.studio/getimage?${params.toString()}`;
}

export function resolveCarVisual(input: { brand?: string; model?: string; makeModel?: string | null }): CarVisual {
  const parsed = input.brand && input.model ? { brand: input.brand, model: input.model } : parseMakeModel(input.makeModel);
  const brand = parsed?.brand ?? 'RideBuddy';
  const model = parsed?.model ?? input.makeModel?.trim() ?? 'Car';
  const hue = hashHue(`${brand} ${model}`);
  return {
    brand,
    model,
    body: MODEL_BODY[model] ?? 'hatch',
    brandColor: BRAND_COLOR[brand] ?? colors.brandBlue,
    accent: hsl(hue, 62, 46),
    code: modelCode(model),
    electric: isElectric(model),
    imageUrl: carImageUrl(brand, model),
  };
}
