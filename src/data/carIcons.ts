function hashHue(text: string): number {
  let n = 0;
  for (let i = 0; i < text.length; i += 1) n = (n * 31 + text.charCodeAt(i)) % 360;
  return n;
}

function hsl(h: number, s: number, l: number): string {
  return `hsl(${h} ${s}% ${l}%)`;
}

export function modelCode(model: string): string {
  const clean = model.replace(/[^A-Za-z0-9]+/g, ' ').trim();
  const parts = clean.split(/\s+/).filter(Boolean);
  if (parts.length >= 2) return `${parts[0][0]}${parts[1][0]}`.toUpperCase();
  return clean.slice(0, 2).toUpperCase() || 'RB';
}

function isElectric(model: string): boolean {
  return /ev|electric|ioniq|e-tron|eqa|eqb|atto|taycan|kona electric|ec3|^e6$|be 6|xev|sealion/i.test(model);
}

